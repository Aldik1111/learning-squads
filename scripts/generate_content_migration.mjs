// Generate this release's additive snapshot once. --check detects content/SQL drift.
import {readFileSync,writeFileSync,existsSync} from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
const read=(file)=>JSON.parse(readFileSync(file,'utf8'));
const quote=value=>"'"+String(value).replaceAll("'","''")+"'";
const nullable=value=>value==null?'null':quote(value);
const catalog=read('content/catalog.json');
assert.equal(catalog.courses.length,6);
const oldVersions=new Map([['python-first-function',1],['ai-clear-requests',1],['spanish-first-conversation',2]]);
const lines=['-- Generated by scripts/generate_content_migration.mjs. Do not rewrite after application.','-- Published versions are checked, never overwritten. New tasks bind to immutable module versions.'];
let count=0;
for(const course of catalog.courses){
 assert.equal(course.modules.length,3);
 for(const [index,entry] of course.modules.entries()){
  const directory=path.join('content',entry.directory),m=read(path.join(directory,'module.json'));
  const keys=read(path.join(directory,m.answerKey));
  assert.equal(m.id,entry.id);
  const quiz=m.quiz.map(q=>{assert.ok(keys[q.id]);return {...q,...keys[q.id]};});
  const quizSql=quote(JSON.stringify(quiz))+'::jsonb';
  if(oldVersions.has(m.id)){
   assert.equal(m.contentVersion,oldVersions.get(m.id),'Published content version must not change in this release');
   lines.push(`do $$ begin if (select quiz from public.ls_content_versions where module_id=${quote(m.id)} and content_version=${m.contentVersion}) is distinct from ${quizSql} then raise exception 'Published quiz snapshot differs: ${m.id}';end if;end $$;`);
  }else lines.push(`insert into public.ls_content_versions(module_id,content_version,quiz) values(${quote(m.id)},${m.contentVersion},${quizSql});`);
  const exercise=m.exercise?read(path.join(directory,m.exercise)):null;
  if(exercise)lines.push(`insert into public.ls_python_exercise_versions values(${quote(exercise.id)},${exercise.exerciseVersion},${quote(JSON.stringify(exercise.cases.map(c=>c.id)))}::jsonb);`);
  lines.push(`insert into public.ls_course_modules values(${quote(m.id)},${quote(course.id)},${m.contentVersion},${index+1},${nullable(m.conversation?.targetLanguage)},${nullable(exercise?.id)},${exercise?.exerciseVersion??'null'});`);
  const task=read(path.join(directory,'task.json'));
  assert.equal(task.id,m.id+'-task');assert.equal(task.version,1);assert.ok(task.acceptanceCriteria.length);
  lines.push(`insert into public.ls_task_definitions values(${quote(task.id)},${task.version},${quote(m.id)},${m.contentVersion},${quote(task.title)},${quote(task.description)},${quote(JSON.stringify(task.acceptanceCriteria))}::jsonb);`);
  count++;
 }
}
assert.equal(count,18);
const destination='supabase/migrations/202611150011_expanded_content.sql';
const output=lines.join('\n')+'\n';
if(process.argv.includes('--check'))assert.equal(readFileSync(destination,'utf8'),output,'Content snapshots drifted from immutable release migration');
else {assert.ok(!existsSync(destination),'Never rewrite an existing migration; create a new version instead');writeFileSync(destination,output);}
console.log(`Six courses / ${count} module and task snapshots ${process.argv.includes('--check')?'verified':'generated'}`);
